"""Compare contact-probe runs across engines: PhysX (check_contact.py) vs Newton (check_contact_newton.py).

    python scripts/compare_engines.py --runs results/newton_vs_physx/physx_ref results/newton_vs_physx/nw_s4_tc4_ell
Writes <out>/COMPARISON.md (table per run x tier) and <out>/overlay_force_vs_depth.png (aligned plug, seed 0).
"""

from __future__ import annotations

import argparse
import gzip
import json
from pathlib import Path

import numpy as np

from patchbench.assets.build_assets import jack_geometry
from patchbench.contact_probe import DIMS, OVERTRAVEL, SPEED, START

ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
ap.add_argument("--runs", nargs="+", type=Path, required=True, help="run dirs with summary.json + traces.csv.gz")
ap.add_argument("--labels", nargs="*", default=None)
ap.add_argument("--plot_first", type=int, default=None, help="overlay only the first N runs (table keeps all)")
ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "results" / "newton_vs_physx")
args = ap.parse_args()


def load(run: Path):
    s = json.loads((run / "summary.json").read_text())
    with gzip.open(run / "traces.csv.gz", "rt") as fh:
        header = fh.readline().strip().split(",")
        rows = [line.strip().split(",") for line in fh]
    cols = {h: np.array([r[i] for r in rows]) for i, h in enumerate(header)}
    for h in header[1:]:
        cols[h] = cols[h].astype(float)
    return s, cols


def label_of(s: dict) -> str:
    c = s["config"]
    if c.get("engine") == "newton":
        coll = "Newton collision" if c.get("contacts") == "newton" else "MuJoCo collision"
        return f"Newton MJWarp, {coll} ({c['substeps']}x substeps, solref {c['solref'][0] * 1e3:.2g} ms, d0 {c['solimp'][0]:g})"
    return f"PhysX TGS ({c['pos_iters']} it, offset {c['contact_offset_m'] * 1e3:g} mm)"


def tier_stats(s: dict, tier: str) -> dict:
    eps = [e for e in s["episodes"] if e["tier"] == tier]
    al = [e for e in eps if e["offset_mm"] == 0 and e["tilt_deg"] == 0]
    n = len(eps)
    return {
        "aligned_latch": np.mean([e["latched"] for e in al]),
        "aligned_sig": np.mean([e["signature"] for e in al]),
        "peak": np.mean([e["peak_axial_N"] for e in al]),
        "latch_all": np.mean([e["latched"] for e in eps]),
        "retained_all": np.mean([e["retained"] for e in eps]),
        "pen_aligned": np.nanmax([e["max_penetration_mm"] for e in al]),
        "pen_all": np.nanmax([e["max_penetration_mm"] for e in eps]),
        "explosions": sum(e["exploded"] for e in eps),
        "tunnels": sum(e["tunnel"] for e in eps),
        "n": n,
    }


def main():
    runs = [load(r) for r in args.runs]
    labels = args.labels or [label_of(s) for s, _ in runs]
    tiers = [t for t in ("loose", "medium", "spec") if any(e["tier"] == t for s, _ in runs for e in s["episodes"])]
    args.out.mkdir(parents=True, exist_ok=True)

    lines = [
        "| run | tier | aligned latch | aligned signature | peak axial N (aligned) | latch rate, all variants | "
        "retained | max pen. aligned / all mm | explosions | tunnels | wall s / sim s |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (s, _), lab, run in zip(runs, labels, args.runs, strict=True):
        for t in tiers:
            st = tier_stats(s, t)
            if not st["n"]:
                continue
            w = s.get("wall_s_per_sim_s")
            w = f"{w:.2f}" if w else "-"
            lines.append(
                f"| {lab} (`{run.name}`) | {t} | {st['aligned_latch']:.2f} | {st['aligned_sig']:.2f} | {st['peak']:.2f} | "
                f"{st['latch_all']:.2f} | {st['retained_all']:.2f} | {st['pen_aligned']:.3f} / {st['pen_all']:.3f} | "
                f"{st['explosions']} | {st['tunnels']} | {w} |"
            )
    # per-variant agreement (latch rate per tier x offset x tilt) between the first run and each other run
    agree = []
    base = runs[0][0]["variants"]
    for (s, _), lab in zip(runs[1:], labels[1:], strict=True):
        keys = [k for k in base if k in s["variants"]]
        d = [abs(base[k]["latch_rate"] - s["variants"][k]["latch_rate"]) for k in keys]
        same = sum(x == 0 for x in d)
        agree.append(f"- {lab} vs {labels[0]}: {same}/{len(keys)} variants with identical latch rate; "
                     f"mean |difference| {np.mean(d):.2f}")  # fmt: skip
    (args.out / "COMPARISON.md").write_text(
        "# Contact probe: engine comparison\n\nGenerated by `scripts/compare_engines.py`.\n\n"
        + "\n".join(lines) + "\n\n" + "\n".join(agree) + "\n"
    )  # fmt: skip
    print((args.out / "COMPARISON.md").read_text())

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    t_push_end = 0.3 + (DIMS.seat_depth + OVERTRAVEL - START) / SPEED
    fig, ax = plt.subplots(2, len(tiers), figsize=(5.5 * len(tiers), 6.5), sharex=True, squeeze=False,
                           constrained_layout=True)  # fmt: skip
    for c, tier in enumerate(tiers):
        g = jack_geometry(DIMS, tier)
        for (_, cols), lab in list(zip(runs, labels, strict=True))[: args.plot_first]:
            sel = (cols["tier"] == tier) & (cols["offset_mm"] == 0) & (cols["tilt_deg"] == 0) & (cols["seed"] == 0)
            sel &= cols["t"] <= t_push_end
            if not sel.any():
                continue
            ax[0, c].plot(cols["depth_mm"][sel], cols["axial_N"][sel], lw=1, label=lab)
            ax[1, c].plot(cols["depth_mm"][sel], cols["latch_deg"][sel], lw=1)
        for a in ax[:, c]:
            for x, lbl in ((g.lip_start, "lip"), (g.catch_depth, "catch"), (g.snap_depth, "snap"),
                           (g.seat_depth, "seat")):  # fmt: skip
                a.axvline(x * 1e3, c="0.75", lw=0.8)
                a.text(x * 1e3, a.get_ylim()[1], lbl, fontsize=7, rotation=90, va="top")
        ax[0, c].set_title(f"{tier} (clearance {g.clearance * 1e3:.3f} mm/side)")
        ax[0, c].set_ylabel("axial contact force [N]")
        ax[1, c].set_ylabel("latch angle from rest [deg]")
        ax[1, c].set_xlabel("plug tip depth [mm]")
        ax[0, c].set_xlim(-2, DIMS.seat_depth * 1e3 + 1.5)
    ax[0, 0].legend(fontsize=7)
    fig.suptitle("Aligned RJ45 insertion (virtual wrist, seed 0): PhysX vs Newton")
    fig.savefig(args.out / "overlay_force_vs_depth.png", dpi=130)
    print(f"wrote {args.out / 'overlay_force_vs_depth.png'}")


if __name__ == "__main__":
    main()
