"""GR00T v0 vs v1 comparison: results/GROOT.md (table) and results/groot_v0_v1.png (dumbbell chart per tier).

Learned policies are reported here, apart from the scripted-controller leaderboard (scripts/leaderboard.py).

    python scripts/groot_report.py [--results results/] [--v0 <results dir name>] [--v1 <results dir name>]
"""

from __future__ import annotations

import argparse
import json
import sys
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))  # run from a checkout without installing

from latchbench import results_io as rio  # noqa: E402

STAGES = ("reached", "contacted", "aligned", "seated", "latched")
TIERS = ("loose", "medium", "spec")
V0_COLOR, V1_COLOR = "#6da7ec", "#184f95"  # one hue, two shades (blue 300 / 600); v0 hollow, v1 filled
INK, INK_2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e6e5e1", "#fcfcfb"


def load(results: Path, name: str) -> dict[str, dict]:
    out = {}
    for t in TIERS:
        p = results / name / f"{t}.json"
        if p.exists():
            out[t] = json.loads(p.read_text())
    return out


def fisher_two_sided(k1: int, n1: int, k2: int, n2: int) -> float:
    """Two-sided Fisher exact test for k1/n1 vs k2/n2."""
    k, n = k1 + k2, n1 + n2

    def p(a: int) -> float:
        return comb(n1, a) * comb(n2, k - a) / comb(n, k)

    p0 = p(k1)
    return sum(p(a) for a in range(max(0, k - n2), min(k, n1) + 1) if p(a) <= p0 * (1 + 1e-9))


def latched(r: dict) -> tuple[int, int]:
    n = int(r["n"])
    return round(r["funnel"]["latched"] * n), n


def markdown(v0: dict, v1: dict, names: tuple[str, str]) -> str:
    lines = [
        "# GR00T N1.7: v0 vs v1",
        "",
        "Generated by `scripts/groot_report.py` from `results/<policy>/<tier>.json`; do not edit by hand.",
        "",
        f"- **v0** `{names[0]}`: demos from the open-loop expert given the true port pose; state = 6 joint positions.",
        f"- **v1** `{names[1]}`: demos from the telemetry-spiral expert given a port estimate with 1.5 mm noise;",
        "  state = 6 joint positions + 6 `Present_Load` registers. Same model, recipe, steps and evaluator.",
        "",
        "Fraction of episodes reaching each stage (n per tier in the last column). Latched: Wilson 95 % interval.",
        "",
        "| tier | model | " + " | ".join(STAGES[:-1]) + " | latched | n |",
        "|---|---|" + "---|" * (len(STAGES) - 1) + "---|---|",
    ]
    k0 = n0 = k1 = n1 = 0
    for t in TIERS:
        if t not in v0 or t not in v1:
            continue
        for tag, r in (("v0", v0[t]), ("v1", v1[t])):
            k, n = latched(r)
            lo, hi = rio.wilson_ci(k, n)
            cells = " | ".join(f"{r['funnel'][s]:.2f}" for s in STAGES[:-1])
            lines.append(f"| {t} | {tag} | {cells} | {k}/{n} = {k / n:.2f} [{lo:.2f}, {hi:.2f}] | {n} |")
        a, b = latched(v0[t]), latched(v1[t])
        k0, n0, k1, n1 = k0 + a[0], n0 + a[1], k1 + b[0], n1 + b[1]
    p = fisher_two_sided(k1, n1, k0, n0)
    lines += ["", f"Pooled over tiers: v0 latched {k0}/{n0}, v1 latched {k1}/{n1} (two-sided Fisher exact p = {p:.3f}).", ""]
    return "\n".join(lines)


def plot(v0: dict, v1: dict, path: Path) -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    tiers = [t for t in TIERS if t in v0 and t in v1]
    fig, axes = plt.subplots(1, len(tiers), figsize=(4.0 * len(tiers), 3.4), sharey=True, facecolor=SURFACE)
    axes = [axes] if len(tiers) == 1 else list(axes)
    ys = list(range(len(STAGES)))[::-1]  # reached on top, latched at the bottom
    for ax, t in zip(axes, tiers):
        ax.set_facecolor(SURFACE)
        for y, s in zip(ys, STAGES):
            a, b = v0[t]["funnel"][s], v1[t]["funnel"][s]
            ax.plot([a, b], [y, y], color=GRID if a == b else "#b9b8b3", lw=2, zorder=1, solid_capstyle="round")
            ax.scatter([a], [y], s=70, facecolor=SURFACE, edgecolor=V0_COLOR, linewidth=2, zorder=3)
            ax.scatter([b], [y], s=70, color=V1_COLOR, edgecolor=SURFACE, linewidth=2, zorder=4)
            right = max(a, b)
            ax.text(right + 0.035, y, f"{b:.2f} ({b - a:+.2f})", va="center", ha="left", fontsize=8.5, color=INK_2)
        ax.set_title(t, fontsize=11, color=INK, loc="left")
        ax.set_xlim(0, 0.85)
        ax.set_xticks([0, 0.2, 0.4, 0.6])
        ax.set_yticks(ys, STAGES)
        ax.tick_params(colors=INK_2, labelsize=9, length=0)
        ax.grid(axis="x", color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.spines["bottom"].set_color(GRID)
        ax.set_xlabel("fraction of episodes", fontsize=9, color=INK_2)
    handles = [
        plt.Line2D([], [], marker="o", ls="", markersize=8, markerfacecolor=SURFACE, markeredgecolor=V0_COLOR,
                   markeredgewidth=2, label="v0: open-loop demos, joint state"),
        plt.Line2D([], [], marker="o", ls="", markersize=8, color=V1_COLOR, label="v1: search demos, joint state + Present_Load"),
    ]
    fig.legend(handles=handles, loc="upper center", ncol=2, frameon=False, fontsize=9, bbox_to_anchor=(0.5, 1.02))
    fig.suptitle("GR00T N1.7 on LatchBench: stage reached per episode, v0 vs v1 (n = 50 per tier)",
                 fontsize=11.5, color=INK, y=1.10)
    fig.tight_layout()
    fig.savefig(path, dpi=160, bbox_inches="tight", facecolor=SURFACE)
    plt.close(fig)
    return path


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", default=str(ROOT / "results"))
    ap.add_argument("--v0", default="lerobot_latchbench-groot-n17")
    ap.add_argument("--v1", default="lerobot_latchbench-groot-n17-load")
    args = ap.parse_args(argv)
    res = Path(args.results)
    v0, v1 = load(res, args.v0), load(res, args.v1)
    assert v0 and v1, f"missing results for {args.v0} or {args.v1} in {res}"
    md = res / "GROOT.md"
    md.write_text(markdown(v0, v1, (args.v0, args.v1)))
    png = plot(v0, v1, res / "groot_v0_v1.png")
    print(md.read_text())
    print(f"wrote {md} and {png}")


if __name__ == "__main__":
    main()
